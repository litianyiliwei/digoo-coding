#!/usr/bin/env python3
"""Generate or verify docs/product/BASELINE-INDEX.md from baseline artifacts.

Usage:
  python scripts/gen-baseline-index.py --write
  python scripts/gen-baseline-index.py --check
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/product/BASELINE-INDEX.md'


def lines(path):
    target = ROOT / path
    if not target.is_file():
        return []
    return target.read_text(encoding='utf-8').splitlines()


def csv_rows(path):
    target = ROOT / path
    if not target.is_file():
        return []
    with target.open(newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def count(path, pattern):
    return len(re.findall(pattern, '\n'.join(lines(path)), re.M))


def status(path):
    for line in lines(path)[:12]:
        match = re.search(r'(?:状态|Status)[:：]\s*([^（(，,]+)', line)
        if match:
            return match.group(1).strip()
    return '—'


def build():
    flow_count = count('docs/product/workflows.md', r'^##\s+(FLOW-\d{3})\b')
    node_count = count('docs/product/workflows.md', r'^\|\s*(NODE-\d{3}-\d{2})\s*\|')
    do_count = len(csv_rows('docs/product/data-objects.csv'))
    rd_count = len(csv_rows('docs/product/rd-matrix.csv'))
    role_rows = csv_rows('docs/product/role-permission-matrix.csv')
    roles = {r.get('role_id', '').strip() for r in role_rows if r.get('role_id')}
    caps = {r.get('capability_id', '').strip() for r in role_rows if r.get('capability_id')}
    br_count = count('docs/product/business-rules.md', r'^\|\s*(BR-\d{3})\s*\|')
    term_count = count('docs/product/glossary.md', r'^\|\s*(TERM-\d{3})\s*\|')
    q_count = count('docs/product/open-questions.md', r'^\|\s*(Q-\d{3})\s*\|')
    dec_count = count('docs/product/decisions.md', r'^\|\s*(DEC-\d{3})\s*\|')
    asm_count = count('docs/product/assumptions.md', r'^\|\s*(ASM-\d{3})\s*\|')
    lesson_count = count('docs/product/lessons.md', r'^\|\s*(LESSON-\d{3})\s*\|')
    brief_lines = len(lines('docs/product/BASELINE-BRIEF.md'))
    req_lines = len(lines('docs/product/requirements-analysis.md'))
    sizing_lines = len(lines('docs/product/change-sizing.md'))
    id_lines = len(lines('docs/product/id-conventions.md'))
    accept_lines = len(lines('docs/product/acceptance-policy.md'))
    artifacts = [
        ('Baseline brief', 'docs/product/BASELINE-BRIEF.md', f'{brief_lines} lines', 'Resident entry point for stages 02–05'),
        ('Requirements business analysis', 'docs/product/requirements-analysis.md', f'{req_lines} lines', 'Index of goals, scope, roles, assumptions, and decisions'),
        ('Business workflows', 'docs/product/workflows.md', f'FLOW {flow_count} / NODE {node_count}', 'Main, alternative, and exception node tables'),
        ('Business data objects', 'docs/product/data-objects.csv', f'{do_count} DOs', 'Business concept catalog, not database tables'),
        ('RD matrix', 'docs/product/rd-matrix.csv', f'{rd_count} RD rows', 'Node → role → DO → access type → verification intent'),
        ('Business rules', 'docs/product/business-rules.md', f'{br_count} BRs', 'Global and feature-level rules with level/enforcement'),
        ('Glossary', 'docs/product/glossary.md', f'{term_count} TERMs', 'Unified vocabulary and forbidden terms'),
        ('Open questions', 'docs/product/open-questions.md', f'{q_count} Qs', 'Open questions, owners, blocking conditions'),
        ('Role-permission matrix', 'docs/product/role-permission-matrix.csv', f'{len(role_rows)} rows / ROLE {len(roles)} / CAP {len(caps)}', 'Anchor for proposal-level permission ACs'),
        ('Slicing and DoD', 'docs/product/change-sizing.md', f'{sizing_lines} lines', 'Change budget, split signals, and definition of done'),
        ('Decision log', 'docs/product/decisions.md', f'{dec_count} DECs', 'Prevents re-litigating settled decisions'),
        ('Assumption register', 'docs/product/assumptions.md', f'{asm_count} ASMs', 'Assumptions, verification method, due point, and owner'),
        ('Lessons/anti-patterns', 'docs/product/lessons.md', f'{lesson_count} LESSONs', 'Reusable failure patterns written back after acceptance'),
        ('ID conventions', 'docs/product/id-conventions.md', f'{id_lines} lines', 'Project-level/Change-level IDs and parallel allocation rules'),
        ('Acceptance policy', 'docs/product/acceptance-policy.md', f'{accept_lines} lines', 'AC format, test mapping, blockers, and evidence requirements'),
        ('Baseline status', 'docs/architecture/baseline-status.md', status('docs/architecture/baseline-status.md'), 'Per-domain versions, freeze state, and approvals'),
    ]
    out = [
        '# Baseline Index (auto-generated)',
        '',
        '> This file is generated by `scripts/gen-baseline-index.py`; do not edit by hand. Run `python scripts/gen-baseline-index.py --write` to update it; `--check` verifies freshness.',
        '',
        '| Artifact | Path | Status/Size | Purpose |',
        '|---|---|---|---|',
    ]
    for name, path, amount, purpose in artifacts:
        exists = (ROOT / path).is_file()
        out.append(f'| {name} | `{path}` | {status(path) if status(path) != "—" else amount}{" (missing)" if not exists else ""} | {purpose} |')
    out.extend(['', '## Current Gaps', ''])
    gaps = []
    if flow_count == 0:
        gaps.append('`workflows.md` has no FLOW node tables.')
    if node_count == 0:
        gaps.append('`workflows.md` has no NODE rows; stage 02 is incomplete.')
    if do_count == 0:
        gaps.append('`data-objects.csv` has only a header.')
    if rd_count == 0:
        gaps.append('`rd-matrix.csv` has only a header.')
    out.extend([f'- {gap}' for gap in gaps] or ['- All machine-readable artifacts are present.'])
    out.extend(['', '## Generation Rules', '',
                '- The index summarizes only paths, status, and counts; it does not copy baseline content.',
                '- Missing artifacts are marked "missing" in the status column; empty files must not satisfy checks.',
                '- Regenerate after status changes or new artifacts; `--check` failure counts as baseline drift.'])
    return '\n'.join(out) + '\n'


def main():
    args = sys.argv[1:]
    if len(args) != 1 or args[0] not in {'--write', '--check'}:
        print('Usage: gen-baseline-index.py --write|--check', file=sys.stderr)
        sys.exit(2)
    content = build()
    if args[0] == '--write':
        OUT.write_text(content, encoding='utf-8')
        print(f'Wrote {OUT.relative_to(ROOT)}')
        return
    if not OUT.is_file():
        print(f'ERROR: missing {OUT.relative_to(ROOT)}; run --write', file=sys.stderr)
        sys.exit(1)
    if OUT.read_text(encoding='utf-8') != content:
        print('ERROR: BASELINE-INDEX.md is stale; run python scripts/gen-baseline-index.py --write', file=sys.stderr)
        sys.exit(1)
    print('Baseline index is up to date.')


if __name__ == '__main__':
    main()
