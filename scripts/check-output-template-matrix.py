#!/usr/bin/env python3
"""Verify that formal output rows in the template matrix point to existing templates/files."""
import csv, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
MATRIX = ROOT / "docs/OUTPUT-TEMPLATE-MATRIX.csv"
errors = []
if not MATRIX.is_file():
    print(f"ERROR: missing {MATRIX}", file=sys.stderr); sys.exit(1)
with MATRIX.open(newline="", encoding="utf-8-sig") as f:
    reader = csv.DictReader(f)
    required = {"phase", "output_name", "template_level", "template_path", "required_traceability", "validator_or_gate", "notes"}
    if not reader.fieldnames or not required.issubset(set(reader.fieldnames)):
        print("ERROR: output template matrix has missing columns", file=sys.stderr); sys.exit(1)
    rows = list(reader)
if not rows:
    errors.append("Output template matrix has no rows")
seen = set()
for line, row in enumerate(rows, 2):
    name = (row.get("output_name") or "").strip()
    level = (row.get("template_level") or "").strip()
    if not name: errors.append(f"line {line}: output_name is required")
    if level not in {"L1", "L2", "L3"}: errors.append(f"line {line}: template_level must be L1/L2/L3")
    key = (row.get("phase", "").strip(), name)
    if key in seen: errors.append(f"line {line}: duplicate phase/output_name {key}")
    seen.add(key)
    path_field = (row.get("template_path") or "").strip()
    if not path_field: errors.append(f"line {line}: template_path is required")
    # Semicolon supports more than one canonical location. OpenSpec-generated artifacts are supplied by its active schema.
    for candidate in [x.strip() for x in path_field.split(";") if x.strip()]:
        if candidate.lower().startswith("openspec 内置 schema") or candidate.lower().startswith("openspec built-in schema"):
            continue
        if candidate.startswith("由 ") or candidate.startswith("generated by "):
            errors.append(f"line {line}: replace free-text template_path with a real template file: {candidate}")
            continue
        target = ROOT / candidate
        if not target.exists(): errors.append(f"line {line}: template path does not exist: {candidate}")
    for col in ("required_traceability", "validator_or_gate"):
        if not (row.get(col) or "").strip(): errors.append(f"line {line}: {col} is required")
for e in errors: print("ERROR:", e)
if errors:
    print(f"Output template matrix check failed: {len(errors)} issue(s).")
    sys.exit(1)
print(f"Output template matrix check passed: {len(rows)} output(s).")
